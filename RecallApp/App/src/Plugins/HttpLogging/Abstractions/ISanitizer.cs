namespace HttpLogging.Abstractions;

/// <summary>
/// Определяет контракт маскирования сенситивных данных в значениях, записываемых в лог.
/// </summary>
/// <remarks>
/// Реализация заменяет значения чувствительных ключей маскирующим значением и рекурсивно
/// обходит вложенные структуры (JSON-объекты и массивы).
/// Данные, не являющиеся строками, JSON-узлами или коллекциями "ключ-значение", возвращаются без изменений.
/// </remarks>
public interface ISanitizer
{
    /// <summary>
    /// Маскирует сенситивные данные в указанном значении.
    /// </summary>
    /// <param name="rawData">Исходное значение.</param>
    /// <returns>
    /// Значение с замаскированными сенситивными данными
    /// или <see langword="null"/>, если <paramref name="rawData"/> равен <see langword="null"/>.
    /// </returns>
    object? Sanitize(object? rawData);
}
